/// Solana-style Context type for Neo N3 smart contracts
/// Provides access to accounts and program state
pub struct Context<'info, T> {
    pub program_id: H160,
    pub accounts: T,
    pub remaining_accounts: Vec<AccountInfo<'info>>,
}

impl<'info, T> Context<'info, T> {
    pub fn new() -> Self {
        Self {
            program_id: Runtime::get_executing_script_hash(),
            accounts: unsafe { core::mem::zeroed() },
            remaining_accounts: Vec::new(),
        }
    }
    
    pub fn with_accounts(accounts: T) -> Self {
        Self {
            program_id: Runtime::get_executing_script_hash(),
            accounts,
            remaining_accounts: Vec::new(),
        }
    }
}

