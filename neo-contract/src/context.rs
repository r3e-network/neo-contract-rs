/// Clock structure for time-related operations
pub struct Clock {
    pub slot: u64,
    pub epoch_start_timestamp: i64,
    pub epoch: u64,
    pub leader_schedule_epoch: u64,
    pub unix_timestamp: i64,
}

impl Clock {
    pub fn get() -> Result<Self> {
        let timestamp = Runtime::get_time();
        Ok(Self {
            slot: 0,
            epoch_start_timestamp: timestamp as i64,
            epoch: 0,
            leader_schedule_epoch: 0,
            unix_timestamp: timestamp as i64,
        })
    }
}

/// Rent structure for account rent calculations
pub struct Rent {
    pub lamports_per_byte_year: u64,
    pub exemption_threshold: f64,
    pub burn_percent: u8,
}

impl Rent {
    pub fn get() -> Result<Self> {
        Ok(Self {
            lamports_per_byte_year: 3480,
            exemption_threshold: 2.0,
            burn_percent: 50,
        })
    }
    
    pub fn minimum_balance(&self, data_len: usize) -> u64 {
        (self.lamports_per_byte_year * data_len as u64 * 2) / 100
    }
}